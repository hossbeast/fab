#pragma once

/*
 * configuration of how to reconcile fsent state with actual filesystem state
 */

#include "types.h"
#include "valyria/llist.h"
#include "stats.h"
#include "descriptor.h"

struct config;
struct fsent;
struct bacon_writer;
struct moria_vertex;

extern llist filesystem_reconcile_list; // struct fsent

typedef union stats_filesystem {
  struct {
      uint32_t stathash;        /* file is stat-hashed */
      uint32_t contenthash;     /* file is content-hashed */
      uint32_t mkdir;           /* directory generated by a pattern is created with mkdir */
      uint32_t readlink;        /* symlink contents read */
      uint32_t fstree_refresh;
  };

  stats_record record;
} stats_filesystem;

extern union stats_filesystem filesystem_stats;
extern struct moria_vertex *g_filesystem;
extern descriptor_type descriptor_stats_filesystem;

void filesystem_reconcile(void);

void filesystem_mkdir_push(struct fsent * restrict fse)
  __attribute__((nonnull));

void filesystem_mkdir_unshift(struct fsent * restrict fse)
  __attribute__((nonnull));

void filesystem_setup(void);

void filesystem_stats_build(bool reset, struct bacon_writer * restrict builder_writer)
  __attribute__((nonnull));

void filesystem_describe(struct bacon_writer * restrict builder_writer)
  __attribute__((nonnull));

size_t filesystem_id_cat(char * dst, size_t sz)
  __attribute__((nonnull));
