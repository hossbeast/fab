#pragma once

#include <sys/types.h>
#include <stdint.h>

#include "descriptor.h"
#include "metadata.h"

extern descriptor_type descriptor_bam_global_stats;
extern descriptor_type descriptor_bam_vertex_stats;
extern descriptor_type descriptor_bam_fsent_dir_stats;
extern descriptor_type descriptor_bam_module_stats;
extern descriptor_type descriptor_bam_formula_stats;
extern descriptor_type descriptor_bam_var_stats;
extern descriptor_type descriptor_bam_config_stats;
extern descriptor_type descriptor_bam_rules_stats;
extern descriptor_type descriptor_bam_rule_stats;

typedef union bam_stats_record {
  char *s[0];
  uint8_t u8[0];
  uint16_t u16[0];
  uint32_t u32[0];
  uint64_t u64[0];
} bam_stats_record;

typedef union bam_global_stats {
    struct {
      /* instantaneous state */
      enum bam_system_state system_state;
      uint8_t system_error;
      uint8_t autorun;

      /* object counts */
      uint32_t modules;                 /* modules */
      uint32_t rules;                   /* rules */
      uint32_t fsents;                  /* fsents */
      uint32_t fsents_shadow;           /* shadow fsents */
      uint32_t rules_files;             /* rules.bam files */
      uint32_t var_files;               /* var.bam files */
      uint32_t config_files;            /* config.bam files */
      uint32_t module_files;            /* module.bam files */
      uint32_t formula_files;           /* .bam formula files */

      /* in_wd lookup index */
      uint32_t notify_index_count;      /* inotify watch descriptors */
      uint32_t notify_index_put;        /* index events */
      uint32_t notify_index_del;        /* disindex events */

      /* dirent lookup index */
      uint32_t fsent_index_count;       /* number of dirents indexed for lookup */
      uint32_t fsent_index_put;         /* index events */
      uint32_t fsent_index_del;         /* disindex events */

      /* event counters */
      uint32_t stathash;                /* file is stat-hashed */
      uint32_t contenthash;             /* file is content-hash */
      uint32_t mkdir;                   /* directory generated by a pattern is created with mkdir */
      uint32_t readlink;                /* symlink contents read */
      uint32_t fstree_refresh;          /* fstree is refreshed */
      uint16_t rules_parse;             /* rules file parse attempt */
      uint16_t rules_parse_ok;          /* rules file parsed successfully */
      uint16_t module_parse;            /* module parse attempt */
      uint16_t module_parse_ok;         /* module parsed successfully */
      uint16_t module_reloaded;         /* module is reloaded */
      uint16_t formula_parse;           /* formula parse attempt */
      uint16_t formula_parse_ok;        /* formula parsed successfully */
      uint16_t var_parse;               /* var.bam parse attempt */
      uint16_t var_parse_ok;            /* var.bam parsed */
      uint16_t config_parse;            /* config.bam parse attempt */
      uint16_t config_parse_ok;         /* config.bam parsed */
      uint16_t rule_run;                /* a rule run attempt */
      uint16_t rule_run_ok;             /* a rule is run */
      uint32_t vertex_stale;            /* vertex marked as stale */
      uint32_t vertex_fresh;            /* vertex marked as fresh */
      uint32_t fml_exec;                /* formula execution attempted */
      uint32_t fml_exec_ok;             /* formula executed successfully */
      uint32_t build_ok;                /* build is run successfully to completion */
      uint16_t system_state_bootstrap;              /* system-state set to bootstrap */
      uint16_t system_state_config_reconcile;       /* system-state set to config-reconcile */
      uint16_t system_state_walker_reconcile;       /* system-state set to walker-reconcile */
      uint16_t system_state_var_reconcile;          /* system-state set to var-reconcile */
      uint16_t system_state_module_reconcile;       /* system-state set to module-reconcile */
      uint16_t system_state_rule_reconcile;         /* system-state set to rule-reconcile */
      uint16_t system_state_bpe_reconcile;          /* system-state set to bpe-reconcile */
      uint16_t system_state_formula_reconcile;      /* system-state set to formula-reconcile */
      uint16_t system_state_filesystem_reconcile;   /* system-state set to filesystem-reconcile */
      uint16_t system_state_building;               /* system-state set to building */
      uint16_t system_state_ok;                     /* system-state set to ok */

      /* devel */
      uint32_t rcu_synchronize_nobody;
      uint32_t rcu_synchronize_wait;
      uint32_t rcu_quiesce_nograce;
      uint32_t rcu_quiesce_notlast;
      uint32_t rcu_quiesce_wake;
  };

  bam_stats_record record;
} bam_global_stats;

typedef union bam_vertex_stats {
  struct {
    const char *path;       /* node absolute path */
    uint16_t path_len;
    const char *id;         /* unique id for the node path */
    uint16_t id_len;
    const char *token;      /* unique id for the node path and node lifetime */
    uint16_t token_len;
    uint32_t type;          /* node type */
    uint32_t state;         /* node state */
    uint8_t indexed_notify; /* whether this node is indexed for lookup by notify descriptor */
    uint8_t indexed_lookup; /* whether this node is indexed for lookup by name */

    /* event counters */
    uint32_t stale;         /* node marked as stale */
    uint32_t fresh;         /* node marked as fresh */
  };

  bam_stats_record record;
} bam_vertex_stats;

/* BAM_FSENT_TYPE_DIR - directory node */
typedef union bam_fsent_dir_stats {
  struct {
    /* directory nodes only */
    uint32_t rules;         /* number of rma references to this directory */
  };

  bam_stats_record record;
} bam_fsent_dir_stats;

/* module vertex stats */
typedef union bam_module_stats {
  struct {
    /* relation/entity counts */
    uint32_t uses_down;
    uint32_t requires_up;
    uint32_t requires_down;
    uint32_t modules_up;
    uint32_t modules_down;
    uint32_t rules;           /* number of rules in the module.bam file */

    /* event counters */
    uint16_t parse;          /* parse attempted */
    uint16_t parse_ok;       /* parsed successfully */
    uint16_t reloaded;       /* module was reloaded */
  };

  bam_stats_record record;
} bam_module_stats;

/* BAM_FSENT_TYPE_RULES_FILE - rules.bam file */
typedef union bam_rules_stats {
  struct {
    /* event counters */
    uint16_t parse;         /* parse attempted */
    uint16_t parse_ok;      /* parsed successfully */

    /* entity counters */
    uint32_t rules;         /* number of rules in this file */
    uint32_t uses_up;       /* count of modules using this rules.bam file */
  };

  bam_stats_record record;
} bam_rules_stats;

/* BAM_NODE_TYPE_FORMULA_FILE - cc.bam file - referenced as formula from a rule */
typedef union bam_formula_stats {
  struct {
    /* event counters */
    uint16_t parse;           /* parse attempted */
    uint16_t parse_ok;        /* parsed successfully */
    uint32_t fml_exec;        /* formula execution attempted */
    uint32_t fml_exec_ok;     /* formula executed successfully */
  };

  bam_stats_record record;
} bam_formula_stats;

/* BAM_FSENT_TYPE_VAR_FILE - var.bam file */
typedef union bam_var_stats {
  struct {
    /* event counters */
    uint16_t parse;          /* parse attempted */
    uint16_t parse_ok;       /* parsed successfully */
  };

  bam_stats_record record;
} bam_var_stats;

/* BAM_FSENT_TYPE_CONFIG_FILE - config.bam file */
typedef union bam_config_stats {
  struct {
    /* event counters */
    uint16_t parse;          /* parse attempted */
    uint16_t parse_ok;       /* parsed successfully */
  };

  bam_stats_record record;
} bam_config_stats;

/* BAM_FSENT_TYPE_SHADOW_RULE //modules/id/rules/id - this represents a rule/module association */
typedef union bam_rule_stats {
  struct {
      uint16_t rule_run;      /* rule is run */
      uint16_t rule_run_ok;   /* rule is run successfully */

      /* results of most recent run */
      uint16_t target_hits;
      uint16_t attachment_hits;
      uint16_t search_hits;          /* nodes matched */
      uint16_t generate_hits;
      uint16_t formula_hits;
      uint16_t dependencies;         /* dependency edges created */
  };

  bam_stats_record record;
} bam_rule_stats;
