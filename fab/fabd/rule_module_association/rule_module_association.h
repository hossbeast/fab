#pragma once

#include "types.h"

#include "valyria/llist.h"
#include "fab/stats.h"
#include "moria.h"
#include "rule_system.h"

struct hashtable;
struct rule;
struct module;
struct graph_invalidation_context;
struct fsedge;

extern llist rma_list;  // active

/*
 * VERTEX_RMA aka rule -> module association
 *
 * These vertices are created when a rule is run in the context of a module.
 */
typedef struct rule_module_association {
  moria_vertex vertex;

  struct fsedge *shadow;       // shadow dirnode //modules/id/rules/id
  fab_vertex_stats vertex_stats;
  fab_rule_stats stats;
  char id[40];                 // hash over rule-id + module-id
  uint16_t id_len;
  char token[40];
  uint16_t token_len;

  /* cached */
  struct formula *fml;         // (EDGE_FML_RMA down)  formula generated by the rule when run (can be null)
  struct rule *rule;           // (EDGE_RULE_RMA down) rule to run
  struct module *mod;          // (EDGE_RMA_MOD up)    module to run the rule in context of
  struct rules *rules;         // (EDGE_RMA_RULES up)  rules file the rule statement is in (can be null)
  struct meta_edge *fml_rma_me;// (down) (nullable)    fml -> rma edge

  struct fsent *dirnode;       // dirnode containing the rules.bam file containing the rule

  /* rule_system state */
//  uint16_t reconciliation_epoch;
  rule_system_work work;
} rule_module_association;

void rule_module_association_setup(void);
void rule_module_association_cleanup(void);

/*
 * idempotent create rule <--> module edge
 *
 * rme    - (returns) rme
 * mod    - module to associate
 * rules  - module which defines the rule
 * rule   - rule to associate
 */
void rule_module_association_create(
    struct rule * restrict rule
  , struct module * mod
  , struct rules * rules
  , struct graph_invalidation_context * restrict invalidation
)
  __attribute__((nonnull(1, 2, 4)));

void rule_module_association_release(
    rule_module_association * restrict rma
  , struct graph_invalidation_context * restrict invalidation
)
  __attribute__((nonnull));

void rule_module_association_init(rule_module_association * restrict rma)
  __attribute__((nonnull));

void rule_module_association_alloc(rule_module_association ** restrict rmap)
  __attribute__((nonnull));

/*
 * Write a config stats to a buffer
 *
 * reset - true to reset the stats while reading them
 * zp    - (returns) number of bytes written to dst
 */
size_t rule_module_association_stats_collate(void *dst, size_t sz, bool reset, rule_module_association *rma)
  __attribute__((nonnull));

void rma_mod_set(
    rule_module_association * restrict rma
  , struct module * restrict mod
  , struct graph_invalidation_context * restrict invalidation
)
  __attribute__((nonnull(1, 3)));
